import { test } from "node:test";
import assert from "node:assert/strict";
import { findMathRanges as f } from "./src/mathRanges.ts";
const i = (from: number, to: number) => ({ from, to, display: false });
const d = (from: number, to: number) => ({ from, to, display: true });
test("inline", () => assert.deepEqual(f("a $x^2$ b"), [i(2, 7)]));
test("display", () => assert.deepEqual(f("$$\\int_0^1 x$$"), [d(0, 14)]));
test("display multiline", () => assert.deepEqual(f("t\n$$\na\\\\\nb\n$$\n"), [d(2, 13)]));
test("escaped", () => assert.deepEqual(f("costa \\$5 e \\$6"), []));
test("escaped inside", () => assert.deepEqual(f("$a\\$b$"), [i(0, 6)]));
test("double backslash not escape", () => assert.deepEqual(f("\\\\$x$"), [i(2, 5)]));
test("space after open", () => assert.deepEqual(f("$ x$ and $y$"), [i(9, 12)]));
test("space before close", () => assert.deepEqual(f("$x $ y$"), [i(0, 7)]));
test("digit after close", () => assert.deepEqual(f("$5 and $10"), []));
test("no newline inline", () => assert.deepEqual(f("$a\nb$"), []));
test("fence", () => assert.deepEqual(f("```\n$x$\n```\n$y$"), [i(12, 15)]));
test("tilde fence longer close", () => assert.deepEqual(f("~~~\n$x$\n~~~~\n$y$"), [i(13, 16)]));
test("unclosed fence", () => assert.deepEqual(f("$a$\n```\n$b$"), [i(0, 3)]));
test("inline code", () => assert.deepEqual(f("`$x$` $y$"), [i(6, 9)]));
test("double backtick", () => assert.deepEqual(f("`` ` $x$ `` $z$"), [i(12, 15)]));
test("unclosed backtick literal", () => assert.deepEqual(f("` $x$"), [i(2, 5)]));
test("backtick in math", () => assert.deepEqual(f("$`a$ `b`"), [i(0, 4)]));
test("unclosed display literal", () => assert.deepEqual(f("$$ a $b$"), [i(5, 8)]));
test("adjacent", () => assert.deepEqual(f("$a$$b$"), [i(0, 3), i(3, 6)]));
test("table cell", () => assert.deepEqual(f("| $\\mathbb{N}$ | $\\mathcal{O}(n)$ |"), [i(2, 14), i(17, 33)]));
test("unicode", () => assert.deepEqual(f("è $x$ ù $$y$$"), [i(2, 5), d(8, 13)]));
test("callout", () => assert.deepEqual(f("> [!thm] T\n> $$\n> a\n> $$"), [d(13, 24)]));
